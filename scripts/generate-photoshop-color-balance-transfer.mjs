import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(process.argv[2]
  ?? 'D:\\mediavibe\\LightTableTests\\AdjustmentParity\\color-balance-transfer');
const preserveRoot = path.resolve(process.argv[3]
  ?? 'D:\\mediavibe\\LightTableTests\\AdjustmentParity\\color-balance-preserve-span');
const preserveOverlapRoot = path.resolve(process.argv[4]
  ?? 'D:\\mediavibe\\LightTableTests\\AdjustmentParity\\color-balance-preserve-overlap');
const manifest = JSON.parse((await readFile(path.join(root, 'photoshop-manifest.json'), 'utf8'))
  .replace(/^\uFEFF/u, ''));
const toneNames = ['shadows', 'midtones', 'highlights'];
const knots = Array.from({ length: 21 }, (_, index) => index * 10 - 100);
const neutral = await sharp(path.join(root, 'photoshop', 'transfer-midtones-0.png'))
  .removeAlpha().raw().toBuffer({ resolveWithObject: true });
const bytes = [];

for (const tone of toneNames) {
  for (const amount of knots) {
    const entry = manifest.find((candidate) => candidate.id === `transfer-${tone}-${amount}`);
    if (!entry) throw new Error(`Missing Color Balance calibration: ${tone} ${amount}`);
    const output = await sharp(entry.file).removeAlpha().raw().toBuffer();
    const sums = new Float64Array(256);
    const counts = new Uint32Array(256);
    for (let pixel = 0; pixel < neutral.info.width * neutral.info.height; pixel += 1) {
      const input = neutral.data[pixel * 3];
      sums[input] += output[pixel * 3];
      counts[input] += 1;
    }
    for (let input = 0; input < 256; input += 1) {
      bytes.push(counts[input] ? Math.round(sums[input] / counts[input]) : input);
    }
  }
}

const preserveManifest = JSON.parse((await readFile(
  path.join(preserveRoot, 'photoshop-manifest.json'), 'utf8'
)).replace(/^\uFEFF/u, ''));
const preserveNeutral = await sharp(path.join(
  preserveRoot, 'photoshop', 'preserve-span-shadows-0.png'
)).removeAlpha().raw().toBuffer({ resolveWithObject: true });
for (const [tone, channel] of [['shadows', 1], ['highlights', 0]]) {
  for (let amount = 0; amount <= 100; amount += 10) {
    const entry = preserveManifest.find((candidate) =>
      candidate.id === `preserve-span-${tone}-${amount}`);
    if (!entry) throw new Error(`Missing preserved Color Balance calibration: ${tone} ${amount}`);
    const output = await sharp(entry.file).removeAlpha().raw().toBuffer();
    const sums = new Float64Array(256);
    const counts = new Uint32Array(256);
    for (let pixel = 0; pixel < preserveNeutral.info.width * preserveNeutral.info.height; pixel += 1) {
      const input = preserveNeutral.data[pixel * 3];
      sums[input] += output[pixel * 3 + channel];
      counts[input] += 1;
    }
    for (let input = 0; input < 256; input += 1) {
      bytes.push(counts[input] ? Math.round(sums[input] / counts[input]) : input);
    }
  }
}

const preserveOverlapManifest = JSON.parse((await readFile(
  path.join(preserveOverlapRoot, 'photoshop-manifest.json'), 'utf8'
)).replace(/^\uFEFF/u, ''));
const preserveOverlapNeutral = await sharp(path.join(
  preserveOverlapRoot, 'photoshop', 'preserve-overlap-0-0.png'
)).removeAlpha().raw().toBuffer({ resolveWithObject: true });
for (let shadowAmount = 0; shadowAmount <= 100; shadowAmount += 10) {
  for (let highlightAmount = 0; highlightAmount <= 100; highlightAmount += 10) {
    const entry = preserveOverlapManifest.find((candidate) =>
      candidate.id === `preserve-overlap-${shadowAmount}-${highlightAmount}`);
    if (!entry) {
      throw new Error(`Missing overlapping preserved Color Balance calibration: `
        + `${shadowAmount} ${highlightAmount}`);
    }
    const output = await sharp(entry.file).removeAlpha().raw().toBuffer();
    const sums = new Float64Array(256);
    const counts = new Uint32Array(256);
    for (let pixel = 0;
      pixel < preserveOverlapNeutral.info.width * preserveOverlapNeutral.info.height;
      pixel += 1) {
      const input = preserveOverlapNeutral.data[pixel * 3];
      sums[input] += output[pixel * 3 + 1];
      counts[input] += 1;
    }
    for (let input = 0; input < 256; input += 1) {
      bytes.push(counts[input] ? Math.round(sums[input] / counts[input]) : input);
    }
  }
}

const base64 = Buffer.from(bytes).toString('base64');
const chunks = base64.match(/.{1,120}/gu) ?? [];
const output = `// Generated by scripts/generate-photoshop-color-balance-transfer.mjs. Do not edit.\n`
  + `export const PHOTOSHOP_COLOR_BALANCE_TRANSFER_WIDTH = 256;\n`
  + `export const PHOTOSHOP_COLOR_BALANCE_TRANSFER_ROWS = 206;\n`
  + `export const PHOTOSHOP_COLOR_BALANCE_PRESERVE_SHADOW_ROW = 63;\n`
  + `export const PHOTOSHOP_COLOR_BALANCE_PRESERVE_HIGHLIGHT_ROW = 74;\n`
  + `export const PHOTOSHOP_COLOR_BALANCE_PRESERVE_OVERLAP_ROW = 85;\n`
  + `export const PHOTOSHOP_COLOR_BALANCE_TRANSFER_BASE64 = [\n`
  + chunks.map((chunk) => `  '${chunk}'`).join(',\n')
  + `\n].join('');\n`;
await writeFile(path.resolve(
  'packages/lighttable-app/src/lighttable/gpu/photoshopColorBalanceTransfer.generated.ts'
), output);
console.log(`Generated ${bytes.length} bytes of Photoshop Color Balance transfer data.`);
