import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(process.argv[2]
  ?? 'D:\\mediavibe\\LightTableTests\\AdjustmentParity\\brightness-contrast\\calibration');
const output = path.resolve(import.meta.dirname, '..',
  'packages/lighttable-app/src/lighttable/gpu/photoshopBrightnessContrastLut.generated.ts');
const manifest = JSON.parse(
  (await readFile(path.join(root, 'photoshop-manifest.json'), 'utf8')).replace(/^\uFEFF/u, '')
);
const parameterKnots = [-150, -125, -100, -75, -50, -25, 0, 25, 50, 75, 100, 125, 150];
const toneCodes = Array.from({ length: 65 }, (_, index) => index === 64 ? 255 : index * 4);

const curveFor = async (id) => {
  const entry = manifest.find((candidate) => candidate.id === id && candidate.status === 'captured');
  if (!entry) throw new Error(`Missing Photoshop calibration case: ${id}.`);
  const image = await sharp(entry.file).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const y = Math.floor(image.info.height / 2);
  return toneCodes.map((input) => {
    const x = Math.round(input / 255 * (image.info.width - 1));
    return image.data[(y * image.info.width + x) * 3];
  });
};
const brightnessCurves = [];
for (const brightness of parameterKnots) {
  const id = brightness === 0
    ? 'brightness-neutral'
    : `brightness-${brightness < 0 ? 'neg' : 'pos'}-${Math.abs(brightness)}`;
  brightnessCurves.push(...await curveFor(id));
}
const negativeContrast = await curveFor('contrast-neg-50');
const positiveContrast = await curveFor('contrast-pos-100');
const format = (values) => values.map((value, index) =>
  `${index % 20 === 0 ? '\n  ' : ''}${value},`).join('');
const source = `// Generated by scripts/generate-photoshop-brightness-contrast-lut.mjs.\n`
  + `// Oracle: Photoshop 27.11, 8-bit untagged RGB interpreted as sRGB.\n`
  + `// Runtime interpolation remains floating point; these bytes are measured curve knots.\n\n`
  + `export const PHOTOSHOP_BRIGHTNESS_CONTRAST_LUT_SIZE = 65;\n`
  + `export const PHOTOSHOP_BRIGHTNESS_PARAMETER_KNOTS = ${JSON.stringify(parameterKnots)} as const;\n\n`
  + `export const PHOTOSHOP_BRIGHTNESS_CURVES = new Uint8Array([${format(brightnessCurves)}\n]);\n\n`
  + `export const PHOTOSHOP_NEGATIVE_CONTRAST_CURVE = new Uint8Array([${format(negativeContrast)}\n]);\n\n`
  + `export const PHOTOSHOP_POSITIVE_CONTRAST_CURVE = new Uint8Array([${format(positiveContrast)}\n]);\n`;
await writeFile(output, source);
process.stdout.write(`Generated ${output}\n`);
