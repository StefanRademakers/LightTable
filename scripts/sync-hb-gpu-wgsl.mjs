import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(fileURLToPath(new URL('..', import.meta.url)));
const harfbuzzRoot = join(repoRoot, '.referenceCode', 'harfbuzz');
const revision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: harfbuzzRoot, encoding: 'utf8' }).trim();
const fragments = [
  'src/hb-gpu-vertex.wgsl',
  'src/hb-gpu-fragment.wgsl',
  'src/hb-gpu-draw-fragment.wgsl'
].map((path) => readFileSync(join(harfbuzzRoot, path), 'utf8'));
const entryPoints = String.raw`
struct LightTableHbGpuUniforms {
  mvp: mat4x4f,
  viewport: vec2f,
  foreground: vec4f,
};

@group(0) @binding(0) var<uniform> lighttable: LightTableHbGpuUniforms;
@group(0) @binding(1) var<storage, read> hb_gpu_atlas: array<vec4<i32>>;

struct LightTableHbGpuVertexInput {
  @location(0) position: vec2f,
  @location(1) texcoord: vec2f,
  @location(2) normal: vec2f,
  @location(3) emPerPos: f32,
  @location(4) glyphLoc: u32,
};

struct LightTableHbGpuVertexOutput {
  @builtin(position) clipPosition: vec4f,
  @location(0) texcoord: vec2f,
  @location(1) @interpolate(flat) glyphLoc: u32,
};

@vertex fn lighttable_hb_gpu_vertex(input: LightTableHbGpuVertexInput) -> LightTableHbGpuVertexOutput {
  let jacobian = vec4f(input.emPerPos, 0.0, 0.0, -input.emPerPos);
  let dilated = hb_gpu_dilate(input.position, input.texcoord, input.normal, jacobian, lighttable.mvp, lighttable.viewport);
  var output: LightTableHbGpuVertexOutput;
  output.clipPosition = lighttable.mvp * vec4f(dilated[0], 0.0, 1.0);
  output.texcoord = dilated[1];
  output.glyphLoc = input.glyphLoc;
  return output;
}

@fragment fn lighttable_hb_gpu_fragment(input: LightTableHbGpuVertexOutput) -> @location(0) vec4f {
  let coverage = hb_gpu_draw(input.texcoord, input.glyphLoc, &hb_gpu_atlas);
  return lighttable.foreground * coverage;
}
`;
const source = [...fragments, entryPoints].join('\n');
const escaped = JSON.stringify(source);
const output = `// Generated by scripts/sync-hb-gpu-wgsl.mjs from HarfBuzz ${revision}.\n`
  + '// HarfBuzz license notices are retained inside the shader source.\n'
  + `export const HB_GPU_SOURCE_REVISION = '${revision}';\n`
  + `export const HB_GPU_DRAW_WGSL = ${escaped};\n`;
writeFileSync(
  join(repoRoot, 'packages', 'text-webgpu', 'src', 'hbGpuShader.generated.ts'),
  output,
  'utf8'
);
